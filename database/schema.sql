-- Import sekali melalui phpMyAdmin. Tidak menghapus database/tabel yang sudah ada.
CREATE DATABASE IF NOT EXISTS siaga_lereng CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE siaga_lereng;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS incidents (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(200) NOT NULL,
 event_date DATE NOT NULL,
 province VARCHAR(100) NOT NULL,
 district VARCHAR(100) NOT NULL,
 location VARCHAR(250) NOT NULL,
 type VARCHAR(60) NOT NULL,
 status VARCHAR(30) NOT NULL,
 deaths INT UNSIGNED NOT NULL DEFAULT 0,
 injured INT UNSIGNED NOT NULL DEFAULT 0,
 missing INT UNSIGNED NOT NULL DEFAULT 0,
 damaged_houses INT UNSIGNED NOT NULL DEFAULT 0,
 notes TEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_date (event_date), INDEX idx_province (province)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS shelters (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 incident_id INT UNSIGNED NOT NULL,
 name VARCHAR(200) NOT NULL,
 location VARCHAR(250) NOT NULL,
 capacity INT UNSIGNED NOT NULL DEFAULT 0,
 occupancy INT UNSIGNED NOT NULL DEFAULT 0,
 needs TEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_shelter_incident FOREIGN KEY (incident_id) REFERENCES incidents(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS people (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 incident_id INT UNSIGNED NOT NULL,
 shelter_id INT UNSIGNED NULL,
 name VARCHAR(200) NOT NULL,
 age TINYINT UNSIGNED NOT NULL,
 status VARCHAR(30) NOT NULL,
 last_location VARCHAR(250) NOT NULL,
 notes TEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_person_incident FOREIGN KEY (incident_id) REFERENCES incidents(id) ON DELETE RESTRICT,
 CONSTRAINT fk_person_shelter FOREIGN KEY (shelter_id) REFERENCES shelters(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
